/**
 * Pure translation lookup with fallback to en-US and parameter interpolation.
 */
export function translate(
  locale: SupportedLocale,
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = translations[locale] || translations['en-US'];
  let text = dict[key] || translations['en-US'][key] || key;

  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }

  return text;
}

/**
 * Translates database entity status strings dynamically.
 */
export function translateStatus(status: string, locale: SupportedLocale = 'en-US'): string {
  const key = `status.${status.toLowerCase()}`;
  return translate(locale, key);
}

/**
 * Translates plumbing preset titles dynamically.
 */
export function translatePreset(title: string, locale: SupportedLocale = 'en-US'): string {
  const lower = title.toLowerCase();
  if (lower.includes('pipe leak') || lower.includes('emergency')) {
    return locale === 'hi' ? 'आपातकालीन पाइप रिपेयर' :
      locale === 'es' ? 'Reparación de Fuga de Emergencia' :
      locale === 'fr' ? 'Réparation Urgence Fuite' :
      locale === 'de' ? 'Notfall-Rohrreparatur' :
      locale === 'ja' ? '緊急配管水漏れ修理' :
      locale === 'zh' ? '紧急管道漏水抢修' : title;
  }
  if (lower.includes('drain') || lower.includes('snaking')) {
    return locale === 'hi' ? 'नाली सफाई व क्लॉग निकासी' :
      locale === 'es' ? 'Desatasco de Desagüe Principal' :
      locale === 'fr' ? 'Débouchage Canalisation Principale' :
      locale === 'de' ? 'Hauptabfluss-Rohrreinigung' :
      locale === 'ja' ? '高圧排水管洗浄・詰まり除去' :
      locale === 'zh' ? '主管道高压疏通' : title;
  }
  if (lower.includes('water heater')) {
    return locale === 'hi' ? 'वाटर हीटर जांच व बदलाव' :
      locale === 'es' ? 'Diagnóstico y Cambio de Calentador' :
      locale === 'fr' ? 'Diagnostic & Remplacement Chauffe-Eau' :
      locale === 'de' ? 'Warmwasserbereiter-Austausch' :
      locale === 'ja' ? '給湯器点検・交換工事' :
      locale === 'zh' ? '热水器故障检修与换新' : title;
  }
  return title;
}
